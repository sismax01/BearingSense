"""Command-line interface for BearingSense.

Provides four primary subcommands:
  1. `bearingsense demo`: Runs the complete end-to-end verification pipeline on physics-informed
     synthetic vibration data (clearly labeled as synthetic), performing leak-free Stratified
     Group K-Fold cross-validation, leakage comparison, out-of-fold permutation importance,
     and generating diagnostic figures + an interactive HTML report.
  2. `bearingsense evaluate`: Runs leak-free evaluation on a folder of real CWRU `.mat` or `.csv`
     recordings (or synthetic `.mat` files) and saves trained model bundles, evaluation metrics,
     plots, and the standalone HTML diagnostic report.
  3. `bearingsense analyze`: Inspects a full `.mat` or `.csv` recording across all sliding windows
     using a trained model bundle and outputs a 4-panel explainable diagnostic figure and JSON report.
  4. `bearingsense serve`: Launches the interactive FastAPI web workbench in the browser.
"""

from __future__ import annotations

import json
from pathlib import Path
import click
import numpy as np
from rich.console import Console
from rich.table import Table

from bearingsense.bearing_kinematics import SKF_6205_DRIVE_END
from bearingsense.data_loader import (
    load_csv_vibration_file,
    load_cwru_mat_file,
    load_directory_dataset,
)
from bearingsense.evaluation import evaluate_models_cross_validation
from bearingsense.explainability import (
    analyze_full_recording,
    compute_permutation_importance,
)
from bearingsense.features import (
    FEATURE_NAMES,
    extract_dataset_features,
)
from bearingsense.modeling import (
    RandomForestBearingClassifier,
    load_model_bundle,
    save_model_bundle,
)
from bearingsense.simulation import (
    generate_synthetic_benchmark_dataset,
)
from bearingsense.visualization import (
    generate_html_diagnostic_dashboard,
    plot_envelope_diagnostics_grid,
    plot_evaluation_summary,
    plot_single_window_inspection,
)

console = Console()


@click.group(context_settings={"help_option_names": ["-h", "--help"]})
@click.version_option(version="0.1.0", prog_name="BearingSense (by SISMAX / sismax01)")
def main() -> None:
    """BearingSense: Explainable Machine Learning & Envelope Spectrum Diagnostics for Bearings."""


@main.command("demo")
@click.option(
    "--output-dir",
    type=click.Path(file_okay=False, dir_okay=True),
    default="outputs/demo_run",
    show_default=True,
    help="Directory where figures, trained model, metrics JSON, and HTML report will be saved.",
)
@click.option(
    "--runs-per-class",
    type=int,
    default=4,
    show_default=True,
    help="Number of independent physical operating runs to simulate per fault class.",
)
@click.option(
    "--snr-db",
    type=float,
    default=2.0,
    show_default=True,
    help="Target Signal-to-Noise Ratio (dB) for synthetic vibration simulation.",
)
@click.option(
    "--seed",
    type=int,
    default=42,
    show_default=True,
    help="Random seed for reproducible simulation and cross-validation.",
)
def run_demo(output_dir: str, runs_per_class: int, snr_db: float, seed: int) -> None:
    """Run complete end-to-end verification pipeline on synthetic bearing vibration data."""
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    console.print(
        "\n[bold cyan]BearingSense [SISMAX Edition] — End-to-End Verification Pipeline (SYNTHETIC SIMULATION DATA)[/bold cyan]"
    )
    console.print(
        "[yellow]Note: Data generated by this command is physics-informed synthetic data intended for "
        "software verification and educational demonstration, not empirical real-world benchmark claims.[/yellow]\n"
    )

    # 1. Generate multi-run synthetic vibration dataset
    console.print(f"[bold]1. Simulating {runs_per_class * 4} independent bearing runs (SNR = {snr_db:.1f} dB)...[/bold]")
    records = generate_synthetic_benchmark_dataset(
        runs_per_class=runs_per_class,
        fs=12000.0,
        duration_sec=2.5,
        snr_db=snr_db,
        seed=seed,
    )

    # 2. Extract 18 domain-engineered features per 2048-sample window
    console.print("[bold]2. Extracting 18 time, frequency, and Hilbert envelope features per window...[/bold]")
    df_features = extract_dataset_features(
        records, window_size=2048, step_size=1024, bearing=SKF_6205_DRIVE_END
    )
    csv_features_path = out_path / "extracted_features_synthetic.csv"
    df_features.to_csv(csv_features_path, index=False)
    console.print(f"   Extracted [green]{len(df_features)}[/green] windows across [green]{df_features['run_id'].nunique()}[/green] distinct runs.")

    # 3. Leak-free Stratified Group K-Fold Cross-Validation & Leakage Comparison
    n_splits = min(4, runs_per_class)
    console.print(f"[bold]3. Running {n_splits}-Fold Leak-Free Stratified Group Cross-Validation...[/bold]")
    cv_results = evaluate_models_cross_validation(
        df_features, n_splits=n_splits, seed=seed, compare_leaky_split=True
    )

    _print_evaluation_table(cv_results)

    # 4. Fit reference Random Forest model & compute Out-of-Fold permutation importance
    console.print("[bold]4. Computing out-of-fold permutation importance and local physical explanations...[/bold]")
    X_all = df_features[FEATURE_NAMES].to_numpy(dtype=np.float64)
    y_all = df_features["label"].to_numpy(dtype=str)

    rf_model = RandomForestBearingClassifier(n_estimators=60, max_depth=6, seed=seed)
    rf_model.fit(X_all, y_all, feature_names=FEATURE_NAMES)

    model_bundle_path = save_model_bundle(
        rf_model,
        X_all,
        y_all,
        out_path / "bearingsense_model_synthetic.json",
        metadata={
            "author_signature": "SISMAX (sismax01)",
            "source_type": "synthetic_simulation",
            "snr_db": snr_db,
            "seed": seed,
        },
    )

    perm_importances = compute_permutation_importance(
        rf_model,
        X_all,
        y_all,
        feature_names=FEATURE_NAMES,
        n_repeats=6,
        seed=seed,
        df_for_oof=df_features,
        n_splits=n_splits,
    )

    # Inspect a sample Outer Race Fault recording across all its windows
    outer_rec = next(r for r in records if r["label"] == "Outer_Race_Fault")
    normal_mask = y_all == "Normal"
    norm_mean = np.mean(X_all[normal_mask], axis=0)
    norm_std = np.maximum(np.std(X_all[normal_mask], axis=0), 1e-9)

    sample_explanation, rep_win = analyze_full_recording(
        signal_1d=outer_rec["signal"],
        fs=float(outer_rec["fs"]),
        rpm=float(outer_rec["rpm"]),
        model=rf_model,
        normal_baseline_mean=norm_mean,
        normal_baseline_std=norm_std,
    )

    # 5. Generate diagnostic figures and interactive HTML report
    console.print("[bold]5. Generating diagnostic plots and standalone HTML dashboard...[/bold]")
    env_grid_png = plot_envelope_diagnostics_grid(records, out_path / "envelope_diagnostics_grid.png")
    eval_sum_png = plot_evaluation_summary(cv_results, perm_importances, out_path / "evaluation_summary.png")
    single_insp_png = plot_single_window_inspection(
        rep_win,
        fs=float(outer_rec["fs"]),
        rpm=float(outer_rec["rpm"]),
        explanation=sample_explanation,
        output_path=out_path / "sample_window_explanation.png",
        source_type="synthetic_simulation",
    )
    html_report = generate_html_diagnostic_dashboard(
        cv_results=cv_results,
        perm_importances=perm_importances,
        sample_explanation=sample_explanation,
        envelope_grid_png=env_grid_png,
        eval_summary_png=eval_sum_png,
        single_inspect_png=single_insp_png,
        output_html_path=out_path / "diagnostic_report.html",
    )

    metrics_json_path = out_path / "evaluation_metrics.json"
    metrics_json_path.write_text(
        json.dumps(
            {
                "author_signature": "SISMAX (sismax01)",
                "data_notice": "SYNTHETIC_SIMULATION_DATA — For software verification only.",
                "cv_results": cv_results,
                "permutation_importance": perm_importances,
                "sample_explanation": sample_explanation,
            },
            indent=2,
        ),
        encoding="utf-8",
    )

    console.print(f"\n[bold green]Success![/bold green] Artifacts written to [cyan]{out_path}[/cyan]:")
    console.print(f"  - HTML Diagnostic Dashboard : {html_report}")
    console.print(f"  - Envelope Spectrum Grid    : {env_grid_png}")
    console.print(f"  - Evaluation Summary Plot   : {eval_sum_png}")
    console.print(f"  - Single Window Explanation : {single_insp_png}")
    console.print(f"  - Metrics & Attribution JSON: {metrics_json_path}")
    console.print(f"  - Trained Model Bundle      : {model_bundle_path}\n")


@main.command("evaluate")
@click.option(
    "--data-dir",
    type=click.Path(exists=True, file_okay=False, dir_okay=True),
    required=True,
    help="Directory containing CWRU .mat or .csv bearing vibration files.",
)
@click.option(
    "--output-dir",
    type=click.Path(file_okay=False, dir_okay=True),
    default="outputs/evaluation",
    show_default=True,
    help="Output directory for evaluation reports, figures, HTML dashboard, and trained model bundle.",
)
@click.option("--folds", type=int, default=4, show_default=True, help="Number of group CV folds.")
@click.option("--seed", type=int, default=42, show_default=True, help="Random seed.")
def run_evaluate(data_dir: str, output_dir: str, folds: int, seed: int) -> None:
    """Evaluate models on a directory of CWRU .mat or .csv vibration recordings."""
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    records = load_directory_dataset(data_dir)
    df_features = extract_dataset_features(records, window_size=2048, step_size=1024)
    cv_results = evaluate_models_cross_validation(df_features, n_splits=folds, seed=seed)

    _print_evaluation_table(cv_results)

    X_all = df_features[FEATURE_NAMES].to_numpy(dtype=np.float64)
    y_all = df_features["label"].to_numpy(dtype=str)
    rf_model = RandomForestBearingClassifier(n_estimators=60, max_depth=6, seed=seed)
    rf_model.fit(X_all, y_all, feature_names=FEATURE_NAMES)

    save_model_bundle(rf_model, X_all, y_all, out_path / "bearingsense_model.json")
    perm_imp = compute_permutation_importance(
        rf_model, X_all, y_all, seed=seed, df_for_oof=df_features, n_splits=folds
    )

    normal_mask = y_all == "Normal"
    norm_mean = np.mean(X_all[normal_mask], axis=0) if np.any(normal_mask) else np.mean(X_all, axis=0)
    norm_std = np.maximum(np.std(X_all[normal_mask], axis=0) if np.any(normal_mask) else np.std(X_all, axis=0), 1e-9)

    sample_rec = next((r for r in records if r["label"] != "Normal"), records[0])
    sample_explanation, rep_win = analyze_full_recording(
        signal_1d=sample_rec["signal"],
        fs=float(sample_rec["fs"]),
        rpm=float(sample_rec["rpm"]),
        model=rf_model,
        normal_baseline_mean=norm_mean,
        normal_baseline_std=norm_std,
    )

    env_grid_png = plot_envelope_diagnostics_grid(records, out_path / "envelope_diagnostics_grid.png")
    eval_sum_png = plot_evaluation_summary(cv_results, perm_imp, out_path / "evaluation_summary.png")
    single_insp_png = plot_single_window_inspection(
        rep_win,
        fs=float(sample_rec["fs"]),
        rpm=float(sample_rec["rpm"]),
        explanation=sample_explanation,
        output_path=out_path / "sample_window_explanation.png",
        source_type=str(sample_rec.get("source_type", "cwru_real")),
    )
    generate_html_diagnostic_dashboard(
        cv_results=cv_results,
        perm_importances=perm_imp,
        sample_explanation=sample_explanation,
        envelope_grid_png=env_grid_png,
        eval_summary_png=eval_sum_png,
        single_inspect_png=single_insp_png,
        output_html_path=out_path / "diagnostic_report.html",
    )
    (out_path / "evaluation_metrics.json").write_text(
        json.dumps(
            {
                "author_signature": "SISMAX (sismax01)",
                "cv_results": cv_results,
                "permutation_importance": perm_imp,
                "sample_explanation": sample_explanation,
            },
            indent=2,
        ),
        encoding="utf-8",
    )
    console.print(f"[bold green]Evaluation complete.[/bold green] Results and HTML dashboard saved to [cyan]{out_path}[/cyan].")


@main.command("analyze")
@click.option(
    "--input-file",
    type=click.Path(exists=True, file_okay=True, dir_okay=False),
    required=True,
    help="Path to a .mat or .csv bearing vibration file to diagnose.",
)
@click.option(
    "--model-path",
    type=click.Path(exists=True, file_okay=True, dir_okay=False),
    required=False,
    default=None,
    help="Optional path to a trained model bundle JSON. If omitted, uses a freshly calibrated synthetic model.",
)
@click.option(
    "--output-dir",
    type=click.Path(file_okay=False, dir_okay=True),
    default="outputs/single_analysis",
    show_default=True,
    help="Directory to write the diagnostic figure and JSON explanation.",
)
@click.option("--fs", type=float, default=12000.0, show_default=True, help="Sampling frequency (Hz).")
@click.option("--rpm", type=float, default=1797.0, show_default=True, help="Shaft speed (RPM).")
def run_analyze(
    input_file: str,
    model_path: str | None,
    output_dir: str,
    fs: float,
    rpm: float,
) -> None:
    """Analyze a full .mat or .csv vibration recording across all sliding windows and explain."""
    in_path = Path(input_file)
    out_path = Path(output_dir)
    out_path.mkdir(parents=True, exist_ok=True)

    if in_path.suffix.lower() == ".mat":
        rec = load_cwru_mat_file(in_path, default_fs=fs, default_rpm=rpm)
    elif in_path.suffix.lower() == ".csv":
        rec = load_csv_vibration_file(in_path, fs=fs, rpm=rpm)
    else:
        raise click.BadParameter(f"Unsupported file extension '{in_path.suffix}'. Expected .mat or .csv.")

    if model_path is not None:
        model, bundle_data = load_model_bundle(model_path)
        norm_mean = np.array(bundle_data["normal_baseline_mean"], dtype=np.float64)
        norm_std = np.array(bundle_data["normal_baseline_std"], dtype=np.float64)
    else:
        sim_recs = generate_synthetic_benchmark_dataset(runs_per_class=4, duration_sec=2.0, seed=42)
        df_tr = extract_dataset_features(sim_recs, window_size=2048, step_size=1024)
        X_tr = df_tr[FEATURE_NAMES].to_numpy(dtype=np.float64)
        y_tr = df_tr["label"].to_numpy(dtype=str)
        model = RandomForestBearingClassifier(n_estimators=50, max_depth=6, seed=42)
        model.fit(X_tr, y_tr, feature_names=FEATURE_NAMES)
        norm_mask = y_tr == "Normal"
        norm_mean = np.mean(X_tr[norm_mask], axis=0)
        norm_std = np.maximum(np.std(X_tr[norm_mask], axis=0), 1e-9)

    explanation, rep_win = analyze_full_recording(
        signal_1d=rec["signal"],
        fs=float(rec["fs"]),
        rpm=float(rec["rpm"]),
        model=model,
        normal_baseline_mean=norm_mean,
        normal_baseline_std=norm_std,
    )
    rec_sum = explanation["recording_summary"]

    fig_path = plot_single_window_inspection(
        window=rep_win,
        fs=float(rec["fs"]),
        rpm=float(rec["rpm"]),
        explanation=explanation,
        output_path=out_path / f"{in_path.stem}_diagnosis.png",
        source_type=str(rec.get("source_type", "unknown")),
    )
    json_path = out_path / f"{in_path.stem}_diagnosis.json"
    json_path.write_text(json.dumps(explanation, indent=2), encoding="utf-8")

    console.print(f"\n[bold]Diagnosis for [cyan]{in_path.name}[/cyan] ({rec_sum['total_windows_evaluated']} windows evaluated):[/bold]")
    console.print(
        f"  Overall Condition   : [bold green]{rec_sum['overall_predicted_class']}[/bold green] "
        f"({rec_sum['mean_class_confidence']:.1%} mean confidence, {rec_sum['window_agreement_ratio']:.1%} window agreement)"
    )
    console.print(f"  Physical Rationale  : {explanation['physical_narrative']}")
    console.print(f"  Saved Figure        : {fig_path}")
    console.print(f"  Saved JSON Report   : {json_path}\n")


@main.command("serve")
@click.option("--host", default="127.0.0.1", show_default=True, help="Bind host address.")
@click.option("--port", type=int, default=8000, show_default=True, help="Bind port.")
def run_serve(host: str, port: int) -> None:
    """Launch the interactive BearingSense FastAPI web workbench."""
    import uvicorn
    from bearingsense.web_app import create_app

    console.print(f"[bold cyan]Starting BearingSense Interactive Workbench [SISMAX] at http://{host}:{port}[/bold cyan]")
    app = create_app()
    uvicorn.run(app, host=host, port=port)


def _print_evaluation_table(cv_results: Dict) -> None:
    table = Table(title="Leak-Free Stratified Group K-Fold Cross-Validation Summary")
    table.add_column("Classifier", style="bold")
    table.add_column("Accuracy", justify="right")
    table.add_column("Balanced Acc.", justify="right")
    table.add_column("Macro Precision", justify="right")
    table.add_column("Macro Recall", justify="right")
    table.add_column("Macro F1 (±SD)", justify="right", style="green")

    for m_name, m_res in cv_results["models"].items():
        table.add_row(
            m_name,
            f"{m_res['accuracy']:.3f}",
            f"{m_res['balanced_accuracy']:.3f}",
            f"{m_res['macro_precision']:.3f}",
            f"{m_res['macro_recall']:.3f}",
            f"{m_res['macro_f1']:.3f} (±{m_res.get('fold_macro_f1_std', 0.0):.3f})",
        )
    console.print(table)


if __name__ == "__main__":
    main()
